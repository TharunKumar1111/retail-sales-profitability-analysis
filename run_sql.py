"""Builds retail.db (SQLite) from the clean CSV and runs every SQL file, saving results to docs/sql_results.md"""
import sqlite3, pandas as pd, re, os
os.makedirs("sql",exist_ok=True)
if os.path.exists("sql/retail.db"): os.remove("sql/retail.db")
con=sqlite3.connect("sql/retail.db")
sch=open("sql/01_schema_and_load.sql").read()
parts=sch.split("-- (run after stg_sales is loaded)")
con.executescript(parts[0])
df=pd.read_csv("data/retail_sales_clean.csv")
df.columns=["order_id","order_date","ship_date","ship_mode","customer_id","customer_name","segment","region","state","city","product_id","category","sub_category","product_name","sales","quantity","discount","profit"]
df.to_sql("stg_sales",con,if_exists="append",index=False)
con.executescript(parts[1])
out=["# SQL query results (auto-generated by run_sql.py)\n"]
for f in ["sql/02_data_quality_checks.sql","sql/03_business_analysis.sql"]:
    txt=open(f).read()
    for m in re.finditer(r"-- @(\w+) ([^\n]*)\n(.*?)(?=\n-- @|\Z)",txt,re.S):
        name,title,q=m.groups(); q=q.strip()
        res=pd.read_sql_query(q,con)
        out.append(f"\n## {name} - {title}\n\n"+res.to_markdown(index=False)+"\n")
        print("OK",name,res.shape)
open("docs/sql_results.md","w").write("\n".join(out))
